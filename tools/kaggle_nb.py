"""Build a Kaggle notebook folder (ipynb + kernel-metadata.json) for one pipeline stage.

Usage (from the repo root, after committing and pushing):
    python tools/kaggle_nb.py --stage setup|sft|dpo [--slug pa2-sft-b] [--sft-slug pa2-sft]
                              [--only task1,task2] [--skip-done] [--allow-dirty]

Then:
    kaggle kernels push -p kaggle/notebooks/<slug> --accelerator NvidiaTeslaT4

The notebook clones the PUBLIC GitHub repo at the current HEAD sha, installs the pinned
requirements without touching Kaggle's torch, prints versions/GPUs, and runs
``python -m pa2.stage --stage <stage>``. Outputs land in /kaggle/working/pa2/outputs/.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def git(*args: str) -> str:
    result = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def code(src: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": src}


def markdown(src: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": src}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--stage", required=True, choices=["setup", "sft", "dpo"])
    parser.add_argument("--slug", default=None, help="kernel slug (default pa2-<stage>)")
    parser.add_argument("--sft-slug", default="pa2-sft", help="kernel whose output holds outputs/sft/best (dpo stage)")
    parser.add_argument("--only", default="", help="comma-separated stage tasks to run")
    parser.add_argument("--skip-done", action="store_true")
    parser.add_argument("--allow-dirty", action="store_true")
    args = parser.parse_args()

    cfg = json.loads((ROOT / "config" / "local.json").read_text(encoding="utf-8"))
    user, repo_url = cfg["kaggle_user"], cfg["repo_url"]

    sha = git("rev-parse", "HEAD")
    if not args.allow_dirty and git("status", "--porcelain", "--untracked-files=no"):
        raise SystemExit("Tracked files have uncommitted changes. Commit and push first (the notebook clones the pushed sha).")
    git("fetch", "origin", "--quiet")
    if not git("branch", "-r", "--contains", sha):
        raise SystemExit(f"HEAD {sha[:10]} is not on origin yet. Run `git push` first.")

    slug = args.slug or f"pa2-{args.stage}"
    stage_cmd = f"python -m pa2.stage --stage {args.stage}"
    if args.only:
        stage_cmd += f" --only {args.only}"
    if args.skip_done:
        stage_cmd += " --skip-done"

    cells = [
        markdown(
            f"# PA2: stage `{args.stage}`\n\n"
            f"Repo: {repo_url} at commit `{sha}`.\n\n"
            "Generated by `tools/kaggle_nb.py`. Outputs are written under `/kaggle/working/pa2/outputs/`."
        ),
        code("!nvidia-smi"),
        code(
            f"!rm -rf /kaggle/working/pa2 && git clone --quiet {repo_url} /kaggle/working/pa2 "
            f"&& cd /kaggle/working/pa2 && git checkout --quiet {sha} && git log -1 --oneline"
        ),
        code(
            "# Keep Kaggle's CUDA-matched torch; remove torchao (known PEFT conflict).\n"
            "!pip uninstall -y -q torchao || true\n"
            "!pip install -q -r /kaggle/working/pa2/requirements.txt\n"
            "!pip install -q -e /kaggle/working/pa2 --no-deps"
        ),
        code(
            "import sys, torch, transformers, datasets, trl, peft\n"
            "print('python', sys.version.split()[0])\n"
            "print('torch', torch.__version__, '| cuda', torch.version.cuda)\n"
            "print('transformers', transformers.__version__, '| datasets', datasets.__version__,\n"
            "      '| trl', trl.__version__, '| peft', peft.__version__)\n"
            "print('GPUs:', torch.cuda.device_count(), [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())])"
        ),
        code(f"!cd /kaggle/working/pa2 && {stage_cmd}"),
        code("!cd /kaggle/working/pa2 && du -sh outputs && find outputs -maxdepth 3 | sort | head -200"),
    ]
    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    metadata = {
        "id": f"{user}/{slug}",
        "title": slug,
        "code_file": f"{slug}.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": "true",
        "enable_gpu": "true",
        "enable_tpu": "false",
        "enable_internet": "true",
        "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [f"{user}/{args.sft_slug}"] if args.stage == "dpo" else [],
        "model_sources": [],
    }
    out_dir = ROOT / "kaggle" / "notebooks" / slug
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{slug}.ipynb").write_text(json.dumps(notebook, indent=1), encoding="utf-8")
    (out_dir / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"Wrote {out_dir.relative_to(ROOT)} for {user}/{slug} at {sha[:10]}")
    print(f"Next: kaggle kernels push -p {out_dir.relative_to(ROOT).as_posix()} --accelerator NvidiaTeslaT4")


if __name__ == "__main__":
    sys.exit(main())
